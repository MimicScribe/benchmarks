#!/usr/bin/env python3
"""fetch_corpus.py — rebuild the public ASR bake-off corpus from its ORIGINAL sources.

The bake-off publishes numbers over 27 files: the 16 AMI meetings in
`corpus.ami_16` and the 11 Earnings-21 calls in `corpus.earnings21_11` of
`benchmark/results/live-transcription-public/pins.json`. NO AUDIO IS
REDISTRIBUTED by this repository. This script downloads each file from the
corpus that publishes it, verifies every byte against a committed SHA-256, and
lays the tree out exactly the way the scorers expect:

    <dest>/ami/audio/<meeting>.wav                       AMI Mix-Headset stream
    <dest>/ami/annotations/words/<meeting>.<X>.words.xml  AMI manual word annotations
    <dest>/ami/rttm/<meeting>.rttm                       BUTSpeechFIT only_words RTTM
    <dest>/ami/uem/<meeting>.uem                         BUTSpeechFIT UEM
    <dest>/earnings21/audio/<id>.wav
    <dest>/earnings21/nlp_references/<id>.nlp            the WER reference
    <dest>/earnings21/rttm/<id>.rttm

`scripts/score_corpus_wer.py` reads `ami/annotations/words/` and
`earnings21/nlp_references/`; the diarization scorers read `rttm/` and `uem/`.
All four are fetched so one command reproduces the whole substrate.

WHAT THE MANIFEST IS, AND WHY IT IS NOT HAND-WRITTEN
----------------------------------------------------
`benchmark/public/asr-bakeoff/corpus_manifest.json` is generated by hashing a
real, already-measured tree (`--emit-manifest`), never typed. A hand-kept hash
list drifts silently: the file it names stays downloadable and the number stops
describing it, and nothing fails. Regenerate with

    python3 scripts/bakeoff/fetch_corpus.py --emit-manifest <benchmark/data dir>

RESUMABLE. A file whose SHA-256 already matches is skipped without a request,
so an interrupted run costs only the files it had not finished. A file that is
present but WRONG is reported and re-downloaded (`--verify-only` reports it and
exits non-zero instead).

AMI's manual word annotations have no per-file URL — they ship inside one
22 MB zip. The zip is fetched only when at least one word file is missing or
mismatched, and only the members this corpus needs are extracted.

Standard library only: urllib, hashlib, zipfile, json, argparse. No requests,
no build, no virtualenv.

Usage
  python3 scripts/bakeoff/fetch_corpus.py --dest ./data
  python3 scripts/bakeoff/fetch_corpus.py --dest ./data --corpus earnings21
  python3 scripts/bakeoff/fetch_corpus.py --verify-only ./data
"""
from __future__ import annotations

import argparse
import hashlib
import json

import shutil
import sys
import urllib.error
import urllib.request
import wave
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve()
REPO = HERE.parent.parent.parent
MANIFEST = REPO / "benchmark" / "public" / "asr-bakeoff" / "corpus_manifest.json"

USER_AGENT = "mimicscribe-bakeoff-corpus-fetch/1 (+https://github.com/mimicscribe/benchmarks)"
CHUNK = 1 << 20


# ── hashing ──────────────────────────────────────────────────────────────────

def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(CHUNK), b""):
            h.update(block)
    return h.hexdigest()


def human(n: float) -> str:
    for unit in ("B", "KB", "MB"):
        if n < 1024:
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024.0
    return f"{n:.1f} GB"


# ── manifest shape ───────────────────────────────────────────────────────────

def load_manifest(path: Path = MANIFEST) -> dict:
    if not path.is_file():
        sys.exit(f"error: manifest not found at {path}")
    with open(path) as f:
        return json.load(f)


def entries(manifest: dict, corpus: str) -> list[dict]:
    """Flatten the manifest into one list of {path, sha256, bytes, url|archive}."""
    out: list[dict] = []
    for item in manifest["files"]:
        if corpus != "all" and item["corpus"] != corpus:
            continue
        out.append({
            "path": item["path"], "sha256": item["sha256"], "bytes": item["bytes"],
            "url": item.get("url"), "archive": item.get("archive"),
            "member": item.get("member"), "label": f'{item["id"]} audio',
        })
        for ref in item["references"]:
            out.append({
                "path": ref["path"], "sha256": ref["sha256"], "bytes": ref["bytes"],
                "url": ref.get("url"), "archive": ref.get("archive"),
                "member": ref.get("member"), "label": f'{item["id"]} {ref["role"]}',
            })
    # References are shared between meetings in no case today, but de-dup by
    # path anyway so a future shared reference cannot be fetched twice.
    seen: set[str] = set()
    unique = []
    for e in out:
        if e["path"] in seen:
            continue
        seen.add(e["path"])
        unique.append(e)
    return unique


# ── download ─────────────────────────────────────────────────────────────────

def download(url: str, dest: Path, expect_sha: str | None, label: str) -> bool:
    """Stream `url` to `dest` via a .part file; rename only on a hash match."""
    dest.parent.mkdir(parents=True, exist_ok=True)
    part = dest.with_suffix(dest.suffix + ".part")
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            total = int(resp.headers.get("Content-Length") or 0)
            h = hashlib.sha256()
            done = 0
            with open(part, "wb") as f:
                while True:
                    block = resp.read(CHUNK)
                    if not block:
                        break
                    f.write(block)
                    h.update(block)
                    done += len(block)
                    # Only redraw in place on a terminal. Piped to a log, a
                    # per-chunk percentage is thousands of junk lines.
                    if total and sys.stdout.isatty():
                        print(f"\r  [get ] {label}  {done * 100 // total}%  ", end="", flush=True)
            got = h.hexdigest()
    except (urllib.error.URLError, urllib.error.HTTPError, OSError) as e:
        print(f"\r  [FAIL] {label}: {e}")
        part.unlink(missing_ok=True)
        return False
    if expect_sha and got != expect_sha:
        print(f"\r  [FAIL] {label}: sha256 mismatch")
        print(f"         expected {expect_sha}")
        print(f"         got      {got}")
        part.unlink(missing_ok=True)
        return False
    part.replace(dest)
    print(f"\r  [ok  ] {label}  {human(done)}          ")
    return True


def fetch_archive_members(manifest: dict, dest: Path, wanted: list[dict]) -> int:
    """Fetch each archive named by `wanted` once and extract only its members.

    Returns the number of members that could NOT be produced.
    """
    by_archive: dict[str, list[dict]] = {}
    for e in wanted:
        by_archive.setdefault(e["archive"], []).append(e)
    failures = 0
    for name, members in by_archive.items():
        spec = manifest["archives"][name]
        local = dest / spec["path"]
        if not (local.is_file() and sha256_of(local) == spec["sha256"]):
            print(f"  [arch] {name}  ({human(spec['bytes'])}, holds "
                  f"{len(members)} needed file(s))")
            if not download(spec["url"], local, spec["sha256"], name):
                failures += len(members)
                continue
        with zipfile.ZipFile(local) as zf:
            for e in members:
                target = dest / e["path"]
                target.parent.mkdir(parents=True, exist_ok=True)
                try:
                    with zf.open(e["member"]) as src, open(target, "wb") as out:
                        shutil.copyfileobj(src, out)
                except KeyError:
                    print(f"  [FAIL] {e['label']}: '{e['member']}' not in {name}")
                    failures += 1
                    continue
                got = sha256_of(target)
                if got != e["sha256"]:
                    print(f"  [FAIL] {e['label']}: extracted sha256 mismatch")
                    target.unlink(missing_ok=True)
                    failures += 1
                else:
                    print(f"  [ok  ] {e['label']}  (from {name})")
    return failures


# ── commands ─────────────────────────────────────────────────────────────────

def cmd_fetch(manifest: dict, dest: Path, corpus: str) -> int:
    todo = entries(manifest, corpus)
    print(f"corpus: {corpus}   dest: {dest}   files: {len(todo)}")
    skipped = 0
    archive_wanted: list[dict] = []
    direct: list[dict] = []
    for e in todo:
        local = dest / e["path"]
        if local.is_file() and local.stat().st_size == e["bytes"] and sha256_of(local) == e["sha256"]:
            skipped += 1
            continue
        (archive_wanted if e.get("archive") else direct).append(e)
    print(f"  already correct: {skipped}   to fetch: {len(direct) + len(archive_wanted)}")

    failures = 0
    for e in direct:
        if not e.get("url"):
            print(f"  [FAIL] {e['label']}: no source URL in the manifest (UNRESOLVED)")
            failures += 1
            continue
        if not download(e["url"], dest / e["path"], e["sha256"], e["label"]):
            failures += 1
    if archive_wanted:
        failures += fetch_archive_members(manifest, dest, archive_wanted)

    print(f"\ndone: {len(todo) - failures} of {len(todo)} file(s) verified, {failures} failed")
    return 1 if failures else 0


def cmd_verify(manifest: dict, root: Path, corpus: str) -> int:
    todo = entries(manifest, corpus)
    match = mismatch = missing = 0
    for e in todo:
        local = root / e["path"]
        if not local.is_file():
            print(f"  MISSING   {e['path']}")
            missing += 1
            continue
        got = sha256_of(local)
        if got == e["sha256"]:
            print(f"  match     {e['path']}")
            match += 1
        else:
            print(f"  MISMATCH  {e['path']}")
            print(f"            expected {e['sha256']}")
            print(f"            got      {got}")
            mismatch += 1
    print(f"\n{match} match / {mismatch} mismatch / {missing} missing "
          f"({len(todo)} in manifest, corpus={corpus})")
    return 1 if (mismatch or missing) else 0


# ── manifest generation ──────────────────────────────────────────────────────

AMI_16 = [
    "EN2002a", "EN2002b", "EN2006b", "ES2002a", "ES2004c", "ES2008c",
    "ES2013b", "ES2016a", "IS1000a", "IS1003b", "IS1006c", "IS1009a",
    "IS1009b", "TS3005a", "TS3009c", "TS3012b",
]
E21_11 = [
    "4320211", "4341191", "4346818", "4359971", "4365024", "4366522",
    "4366893", "4367535", "4383161", "4384964", "4387332",
]
# Which BUTSpeechFIT split directory holds each meeting's RTTM/UEM. The URL is
# split-parameterised, and a wrong split 404s rather than serving the wrong
# file, so this map is checkable: every entry below was confirmed by a live
# fetch whose bytes hash-matched the local copy.
AMI_SPLIT = {m: ("test" if m in {"EN2002a", "EN2002b", "ES2004c", "IS1009a", "IS1009b"}
                 else "train") for m in AMI_16}

AMI_AUDIO_URL = ("https://groups.inf.ed.ac.uk/ami/AMICorpusMirror/amicorpus"
                 "/{m}/audio/{m}.Mix-Headset.wav")
AMI_RTTM_URL = ("https://raw.githubusercontent.com/BUTSpeechFIT/AMI-diarization-setup"
                "/main/only_words/rttms/{split}/{m}.rttm")
AMI_UEM_URL = ("https://raw.githubusercontent.com/BUTSpeechFIT/AMI-diarization-setup"
               "/main/uems/{split}/{m}.uem")
AMI_MANUAL_ZIP_URL = ("https://groups.inf.ed.ac.uk/ami/AMICorpusAnnotations"
                      "/ami_public_manual_1.6.2.zip")
E21_AUDIO_URL = "https://huggingface.co/datasets/Revai/earnings21/resolve/main/wav/{i}.wav"
E21_NLP_URL = ("https://raw.githubusercontent.com/revdotcom/speech-datasets"
               "/master/earnings21/transcripts/nlp_references/{i}.nlp")
E21_RTTM_URL = ("https://raw.githubusercontent.com/revdotcom/speech-datasets"
                "/master/earnings21/rttms/{i}.rttm")

AMI_LICENSE = "CC BY 4.0 (https://groups.inf.ed.ac.uk/ami/corpus/license.shtml)"
E21_TEXT_LICENSE = "CC BY-SA 4.0 (earnings21/LICENSE.md in revdotcom/speech-datasets)"
E21_AUDIO_LICENSE = (
    "Not separately licensed by the publisher; the repository's LICENSE.md covers "
    "'the transcripts and associated text files'. Audio is fetched from the "
    "publisher, never redistributed here."
)


def wav_seconds(path: Path) -> float | None:
    try:
        with wave.open(str(path)) as w:
            return round(w.getnframes() / float(w.getframerate()), 3)
    except Exception:
        return None


def _file_rec(root: Path, rel: str, url: str | None, role: str, license_: str,
              redistributable: bool, archive: str | None = None,
              member: str | None = None) -> dict:
    p = root / rel
    if not p.is_file():
        sys.exit(f"error: --emit-manifest source is missing {rel}")
    rec = {"role": role, "path": rel, "sha256": sha256_of(p),
           "bytes": p.stat().st_size, "license": license_,
           "redistributable": redistributable}
    if archive:
        rec["archive"] = archive
        rec["member"] = member
    else:
        rec["url"] = url
    return rec


def cmd_emit(root: Path, out: Path) -> int:
    print(f"hashing {root} …")
    files: list[dict] = []

    for m in AMI_16:
        audio_rel = f"ami/audio/{m}.wav"
        audio = root / audio_rel
        if not audio.is_file():
            sys.exit(f"error: missing {audio_rel}")
        refs = [
            _file_rec(root, f"ami/rttm/{m}.rttm",
                      AMI_RTTM_URL.format(split=AMI_SPLIT[m], m=m),
                      "rttm", "CC BY 4.0 (BUTSpeechFIT/AMI-diarization-setup, "
                      "derived from AMI manual transcription)", True),
            _file_rec(root, f"ami/uem/{m}.uem",
                      AMI_UEM_URL.format(split=AMI_SPLIT[m], m=m),
                      "uem", "CC BY 4.0 (BUTSpeechFIT/AMI-diarization-setup)", True),
        ]
        for xml in sorted((root / "ami" / "annotations" / "words").glob(f"{m}.*.words.xml")):
            rel = f"ami/annotations/words/{xml.name}"
            refs.append(_file_rec(root, rel, None, "words_xml", AMI_LICENSE, True,
                                  archive="ami_public_manual_1.6.2.zip",
                                  member=f"words/{xml.name}"))
        files.append({
            "id": m, "corpus": "ami", "role": "audio", "path": audio_rel,
            "url": AMI_AUDIO_URL.format(m=m), "sha256": sha256_of(audio),
            "bytes": audio.stat().st_size, "duration_seconds": wav_seconds(audio),
            "license": AMI_LICENSE, "redistributable": False,
            "stream": "Mix-Headset", "split": AMI_SPLIT[m], "references": refs,
        })
        print(f"  ami {m}: audio + {len(refs)} reference file(s)")

    for i in E21_11:
        audio_rel = f"earnings21/audio/{i}.wav"
        audio = root / audio_rel
        if not audio.is_file():
            sys.exit(f"error: missing {audio_rel}")
        refs = [
            _file_rec(root, f"earnings21/nlp_references/{i}.nlp",
                      E21_NLP_URL.format(i=i), "nlp_reference", E21_TEXT_LICENSE, True),
            _file_rec(root, f"earnings21/rttm/{i}.rttm",
                      E21_RTTM_URL.format(i=i), "rttm", E21_TEXT_LICENSE, True),
        ]
        files.append({
            "id": i, "corpus": "earnings21", "role": "audio", "path": audio_rel,
            "url": E21_AUDIO_URL.format(i=i), "sha256": sha256_of(audio),
            "bytes": audio.stat().st_size, "duration_seconds": wav_seconds(audio),
            "license": E21_AUDIO_LICENSE, "redistributable": False,
            "references": refs,
        })
        print(f"  earnings21 {i}: audio + {len(refs)} reference file(s)")

    zip_rel = "ami/annotations/ami_manual.zip"
    zp = root / zip_rel
    if not zp.is_file():
        sys.exit(f"error: missing {zip_rel} — needed to pin the AMI annotation archive")
    archives = {
        "ami_public_manual_1.6.2.zip": {
            "path": zip_rel, "url": AMI_MANUAL_ZIP_URL, "sha256": sha256_of(zp),
            "bytes": zp.stat().st_size, "license": AMI_LICENSE,
            "note": ("AMI manual annotations. Only the `words/` members this corpus "
                     "needs are extracted; the archive itself is an intermediate and "
                     "may be deleted after extraction."),
        }
    }

    ami_files = [f for f in files if f["corpus"] == "ami"]
    e21_files = [f for f in files if f["corpus"] == "earnings21"]
    manifest = {
        "_what": ("Per-file provenance and SHA-256 for the 27-file public ASR "
                  "bake-off corpus. Generated by hashing a measured tree; never "
                  "hand-edited. NO AUDIO IS REDISTRIBUTED — this file is how a "
                  "reader rebuilds it from the publishers and proves the bytes match."),
        "_generated_by": "scripts/bakeoff/fetch_corpus.py --emit-manifest",
        "_pins": ("benchmark/results/live-transcription-public/pins.json "
                  "corpus.ami_16 + corpus.earnings21_11"),
        "layout_root": "benchmark/data",
        "corpora": {
            "ami": {
                "name": "AMI Meeting Corpus",
                "files": len(ami_files),
                "audio_seconds": round(sum(f["duration_seconds"] or 0 for f in ami_files), 1),
                "audio_stream": "Mix-Headset",
                "audio_stream_note": (
                    "The headset MIXDOWN (near-field lapel/headset channels summed to "
                    "one 16 kHz mono track), NOT a distant array microphone. Confirmed "
                    "byte-for-byte: an HTTP Range read of the mirror's "
                    "EN2002a.Mix-Headset.wav hashes identically to the local "
                    "ami/audio/EN2002a.wav, while Array1-01 and Array2-01 hash "
                    "differently at the same offset."),
                "license": AMI_LICENSE,
                "cite": ("Carletta, J. et al. (2005). The AMI Meeting Corpus: "
                         "A Pre-announcement."),
                "reference_for_wer": "ami/annotations/words/<meeting>.<X>.words.xml",
            },
            "earnings21": {
                "name": "Earnings-21",
                "files": len(e21_files),
                "audio_seconds": round(sum(f["duration_seconds"] or 0 for f in e21_files), 1),
                "license_text": E21_TEXT_LICENSE,
                "license_audio": E21_AUDIO_LICENSE,
                "cite": ("Del Rio, M. et al. (2021). Earnings-21: A Practical "
                         "Benchmark for ASR in the Wild. Interspeech 2021."),
                "reference_for_wer": "earnings21/nlp_references/<id>.nlp",
            },
        },
        "archives": archives,
        "files": files,
    }
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w") as f:
        json.dump(manifest, f, indent=2)
        f.write("\n")
    n_refs = sum(len(f["references"]) for f in files)
    print(f"\nwrote {out}: {len(files)} audio file(s) + {n_refs} reference file(s) "
          f"+ {len(archives)} archive(s)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dest", type=Path, default=REPO / "benchmark" / "data",
                    help="where to build the corpus tree (default: <repo>/benchmark/data)")
    ap.add_argument("--verify-only", type=Path, metavar="DIR",
                    help="hash an existing tree against the manifest and exit "
                         "non-zero on any mismatch or missing file")
    ap.add_argument("--corpus", choices=("ami", "earnings21", "all"), default="all")
    ap.add_argument("--manifest", type=Path, default=MANIFEST)
    ap.add_argument("--emit-manifest", type=Path, metavar="SRC_DIR",
                    help="regenerate the manifest by hashing an existing tree "
                         "(writes to --manifest)")
    args = ap.parse_args()

    if args.emit_manifest:
        return cmd_emit(args.emit_manifest.resolve(), args.manifest)
    manifest = load_manifest(args.manifest)
    if args.verify_only:
        return cmd_verify(manifest, args.verify_only.resolve(), args.corpus)
    return cmd_fetch(manifest, args.dest.resolve(), args.corpus)


if __name__ == "__main__":
    sys.exit(main())
